import type { Metadata } from "next";
import Link from "next/link";
import { GrowBar } from "@/components/motion";
import { PageHead, Section } from "@/components/ui";
import { getReport, imagesReport, listCharacters, nanokaReport } from "@/server/repos";

export const metadata: Metadata = { title: "Data Status", description: "Live coverage and quality report for the Tideforge dataset." };

export default function DataStatusPage() {
  const r = getReport();
  const sev = (s: string) => r.issues.filter((i) => i.severity === s);
  const errors = sev("error");
  const chars = listCharacters();
  const nk = nanokaReport();
  const im = imagesReport();
  const imgTotal = im.files.characters + im.files.weapons + im.files.echoes + im.files.sonatas + im.files.elements;
  const rows = [
    { label: `Resonator stat curves (datamine ${nk.version})`, ok: nk.characters.withRealCurves, total: nk.characters.ours },
    { label: "Weapon ATK / secondary-stat curves (datamine)", ok: nk.weapons.withRealCurves, total: nk.weapons.ours },
    { label: "Mirrored art files (icons, portraits, elements)", ok: imgTotal, total: imgTotal + im.failed.length + Object.values(im.unmatched).flat().length * 1 },
  ];
  return (
    <div>
      <PageHead kicker="Trust" title="Data Status">We show what is missing instead of hiding it. This report is generated by the data pipeline (<code>npm run data:build</code>) on every run.</PageHead>
      <p className="mb-6 text-[13px] text-dim">Game version {r.gameVersion} · generated {r.generatedAt.slice(0, 10)} · {r.counts.characters} Resonators, {r.counts.weapons} weapons, {r.counts.echoes} Echoes, {r.counts.sonatas} Sonata sets, {r.counts.banners} banners, {r.counts.events} events.</p>
      <Section title="Coverage">
        <div className="card divide-y divide-line">
          {r.coverage.map((c) => {
            const p = (c.ok / (c.total || 1)) * 100;
            return (
              <div key={c.label} className="grid items-center gap-2 p-3 text-[13.5px] md:grid-cols-[1fr_220px_80px]">
                <span>{c.label}</span><GrowBar pct={p} color={p === 100 ? "var(--color-ok)" : p > 85 ? "var(--color-warn)" : "var(--color-bad)"} /><span className="num text-right">{c.ok}/{c.total}</span>
              </div>
            );
          })}
        </div>
      </Section>
      <Section title="Datamine and art" sub={`Real per-level data from nanoka.cc (game ${nk.version}, fetched ${nk.generatedAt}) and mirrored art (${im.generatedAt}). Unmatched: ${[...nk.characters.unmatched, ...im.unmatched.characters].filter((v, i, a) => a.indexOf(v) === i).join(", ") || "none"}.`}>
        <div className="card divide-y divide-line">
          {rows.map((c) => {
            const p = (c.ok / (c.total || 1)) * 100;
            return (
              <div key={c.label} className="grid items-center gap-2 p-3 text-[13.5px] md:grid-cols-[1fr_220px_80px]">
                <span>{c.label}</span><GrowBar pct={p} color={p === 100 ? "var(--color-ok)" : p > 85 ? "var(--color-warn)" : "var(--color-bad)"} /><span className="num text-right">{c.ok}/{c.total}</span>
              </div>
            );
          })}
        </div>
      </Section>
      <Section title="Cleaned automatically" sub="Problems found in the raw wiki scrape and fixed by the pipeline.">
        <ul className="card divide-y divide-line">{r.fixes.map((f) => <li key={f.label} className="flex justify-between gap-4 p-3 text-[13.5px]"><span>{f.label}</span><span className="num text-ok">×{f.count}</span></li>)}</ul>
      </Section>
      <Section title={`Open errors (${errors.length})`} sub="Real gaps that affect results. These need better sources (game files) rather than more scraping.">
        <div className="card overflow-x-auto"><table className="tbl"><thead><tr><th>Entity</th><th>Issue</th></tr></thead><tbody>
          {errors.map((i, k) => <tr key={k}><td className="whitespace-nowrap font-medium">{chars.find((c) => c.slug === i.entity) ? <Link href={`/characters/${i.entity}`} className="text-accent">{i.entity}</Link> : i.entity}</td><td className="text-mute">{i.message}</td></tr>)}
          {errors.length === 0 && <tr><td colSpan={2} className="text-dim">No open errors.</td></tr>}
        </tbody></table></div>
      </Section>
      <Section title={`Warnings (${sev("warn").length}) and notes (${sev("info").length})`}>
        <details className="card p-4"><summary className="cursor-pointer text-[13px] text-mute">Show all</summary>
          <ul className="mt-3 grid gap-1 text-[12.5px] text-dim">{[...sev("warn"), ...sev("info")].map((i, k) => <li key={k}><span className="text-mute">{i.entity}</span>: {i.message}</li>)}</ul>
        </details>
      </Section>
      <p className="mt-6 text-[12.5px] text-dim">Known root cause: descriptive fields still come from a wiki scrape (<ConfidenceBadgeInline />). Numbers are being moved to datamined game files phase by phase, see <Link href="https://github.com/RishabhRaj7/tideforge/blob/main/docs/ROADMAP.md" className="text-accent">the roadmap</Link>.</p>
    </div>
  );
}
function ConfidenceBadgeInline() { return <span className="text-warn">community confidence</span>; }
